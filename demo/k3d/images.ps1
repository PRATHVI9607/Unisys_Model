# Build the KubeHeal images and push them to the cluster registry (demo branch only).
#   .\demo\k3d\images.ps1                      build and push everything
#   .\demo\k3d\images.ps1 -Only executor,fusion-agent
# V5-I2: `inference-server` is the LightGBM inference service (dockerfiles/Dockerfile.inference, no torch base needed).
# The three neural model-server images are still built, but the chart only deploys them with
# modelServers.legacy.enabled=true (default false).
# Every build gets a fresh tag (b<timestamp>), because the nodes use IfNotPresent and would keep an old
# image under a reused tag. The per-image tags are kept in demo/k3d/.image-tags.json and written to
# demo/k3d/.generated-values.yaml, which up.ps1 passes to Helm (both ignored by git).
# Images come from the registry, so a running pod's imageID is `repo@sha256:<digest>`; the restore path needs
# that form (an image loaded with `k3d image import` only reports a bare image id).
param(
    [string[]]$Only = @(),
    [ValidatePattern('^[a-z0-9][a-z0-9-]{0,39}$')]
    [string]$TargetCluster = "kubeheal",
    [ValidateRange(0, 65535)]
    [int]$TargetRegistryPort = 0
)

. "$PSScriptRoot\lib.ps1"
if ($TargetRegistryPort -eq 0) { $TargetRegistryPort = if ($TargetCluster -eq "kubeheal") { 5150 } else { 5151 } }
$script:ClusterName = $TargetCluster
$script:Context = "k3d-$TargetCluster"
$script:RegistryName = "$TargetCluster-registry"
$script:RegistryHostPort = $TargetRegistryPort
$script:RegistryHost = "localhost:$TargetRegistryPort"
$script:RegistryInCluster = "$($script:RegistryName):5000"
Initialize-Tools -SkipK3d -SkipHelm
Set-Location $RepoRoot

# name -> Dockerfile
$images = [ordered]@{
    "health-agent"          = "dockerfiles/Dockerfile.health"
    "security-agent"        = "dockerfiles/Dockerfile.security"
    "fusion-agent"          = "dockerfiles/Dockerfile.fusion"
    "executor"              = "dockerfiles/Dockerfile.executor"
    "dashboard"             = "dockerfiles/Dockerfile.dashboard"
    "inference-server"      = "dockerfiles/Dockerfile.inference"
    "health-model-server"   = "dockerfiles/Dockerfile.health_model"
    "security-model-server" = "dockerfiles/Dockerfile.security_model"
    "dcm-server"            = "dockerfiles/Dockerfile.dcm"
}

$tag = "b" + (Get-Date -Format "yyyyMMddHHmmss")
$needsBase = ($Only.Count -eq 0) -or ($Only | Where-Object { $_ -match 'model-server|dcm' })
if ($needsBase) {
    $have = docker images kubeheal/base:v4 --format '{{.ID}}'
    if (-not $have) {
        Say "building kubeheal/base:v4 (torch, this is the slow one)"
        docker build -t kubeheal/base:v4 -f dockerfiles/Dockerfile.base .
        if ($LASTEXITCODE -ne 0) { throw "base image build failed" }
    }
}

$built = @()
foreach ($name in $images.Keys) {
    if ($Only.Count -gt 0 -and $Only -notcontains $name) { continue }
    $ref = "$RegistryHost/kubeheal/${name}:$tag"
    Say "building $ref"
    docker build -t $ref -f $images[$name] .
    if ($LASTEXITCODE -ne 0) { throw "build of $name failed" }
    docker push $ref | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "push of $name failed (is the registry $RegistryHost up?)" }
    $built += $name
}

# the demo workloads
if ($Only.Count -eq 0 -or $Only -contains "victim-app") {
    $ref = "$RegistryHost/kubeheal/victim-app:$tag"
    Say "building $ref"
    docker build -t $ref demo/victim-app
    if ($LASTEXITCODE -ne 0) { throw "victim-app build failed" }
    docker push $ref | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "victim-app push failed" }
    $built += "victim-app"
}
if ($Only.Count -eq 0 -or $Only -contains "ransomware-sim") {
    $ref = "$RegistryHost/kubeheal/ransomware-sim:$tag"
    Say "building $ref"
    docker build -t $ref -f dockerfiles/Dockerfile.ransomware .
    if ($LASTEXITCODE -ne 0) { throw "ransomware-sim build failed" }
    docker push $ref | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "ransomware-sim push failed" }
    $built += "ransomware-sim"
}

# Values for Helm: each KubeHeal image from the in-cluster registry name, with the tag it was last built with.
$tagFile = if ($TargetCluster -eq "kubeheal") { Join-Path $PSScriptRoot ".image-tags.json" } else { Join-Path $PSScriptRoot ".image-tags-$TargetCluster.json" }
$tags = @{}
if (Test-Path $tagFile) { (Get-Content $tagFile -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object { $tags[$_.Name] = $_.Value } }
foreach ($b in $built) { $tags[$b] = $tag }
$tags | ConvertTo-Json | Set-Content -Path $tagFile -Encoding ascii
$missing = @($images.Keys | Where-Object { -not $tags.ContainsKey($_) })
if ($missing.Count -gt 0) {
    Warn "pushed: $($built -join ', ') with tag $tag. Helm values NOT written yet, no tag recorded for: $($missing -join ', ')"
    return
}
function T([string]$n) { return $tags[$n] }
$prefix = "$RegistryInCluster/kubeheal"
$yaml = @"
# Generated by demo/k3d/images.ps1 on $(Get-Date -Format s). Do not edit; not committed.
healthAgent: {image: {repository: $prefix/health-agent, tag: $(T 'health-agent')}}
securityAgent: {image: {repository: $prefix/security-agent, tag: $(T 'security-agent')}}
fusionAgent: {image: {repository: $prefix/fusion-agent, tag: $(T 'fusion-agent')}}
executor: {image: {repository: $prefix/executor, tag: $(T 'executor')}}
dashboard: {image: {repository: $prefix/dashboard, tag: $(T 'dashboard')}}
inference: {image: {repository: $prefix/inference-server, tag: $(T 'inference-server')}}
modelServers:
  health: {image: {repository: $prefix/health-model-server, tag: $(T 'health-model-server')}}
  security: {image: {repository: $prefix/security-model-server, tag: $(T 'security-model-server')}}
  dcm: {image: {repository: $prefix/dcm-server, tag: $(T 'dcm-server')}}
"@
$generatedValues = if ($TargetCluster -eq "kubeheal") { Join-Path $PSScriptRoot ".generated-values.yaml" } else { Join-Path $PSScriptRoot ".generated-values-$TargetCluster.yaml" }
Set-Content -Path $generatedValues -Value $yaml -Encoding utf8
Say "pushed: $($built -join ', ') with tag $tag"
